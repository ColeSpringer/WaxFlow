// streamTypeName names a Stream Properties stream type for a refusal message,
// falling back to the raw GUID so an unknown one is still identifiable.
func streamTypeName(g guid) string {
	switch g {
	case guidAudioMedia:
		return "audio"
	case guidVideoMedia:
		return "video"
	case guidCommandMedia:
		return "command"
	case guidBinaryMedia:
		return "binary"
	default:
		return "stream type " + g.String()
	}
}
