package asf

import (
	"encoding/binary"
	"fmt"
)

var le = binary.LittleEndian

// guid is an ASF object identifier in the byte order it appears on the wire:
// the first three fields little-endian, the trailing eight bytes as written.
// Comparing the raw form directly is what the parser wants, so nothing here
// converts to the textual form except String, for messages.
type guid [16]byte

// String renders the canonical 8-4-4-4-12 text, undoing the wire order of the
// first three fields. Only diagnostics use it.
func (g guid) String() string {
	return fmt.Sprintf("%08X-%04X-%04X-%02X%02X-%02X%02X%02X%02X%02X%02X",
		le.Uint32(g[0:]), le.Uint16(g[4:]), le.Uint16(g[6:]),
		g[8], g[9], g[10], g[11], g[12], g[13], g[14], g[15])
}

// guidAt reads the GUID at the start of b, which must hold 16 bytes.
func guidAt(b []byte) guid {
	var g guid
	copy(g[:], b)
	return g
}

