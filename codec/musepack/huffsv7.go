// sv7BookSet is the built SV7 decoders.
type sv7BookSet struct {
	hdr, scfi, dscf *vlc
	q               [7][2]*vlc
}

// sv7Books builds the books once per process: they are read-only and a
// decoder per live stream would otherwise redo the walk.
var sv7Books = sync.OnceValue(func() *sv7BookSet {
	s := &sv7BookSet{
		hdr:  newBook(tableHuffHdr, nil),
		scfi: newBook(tableHuffSCFI, nil),
		dscf: newBook(tableHuffDSCF, nil),
	}
	q := [7][2][]huffEntry{tableHuffQ1, tableHuffQ2, tableHuffQ3, tableHuffQ4, tableHuffQ5, tableHuffQ6, tableHuffQ7}
	for i := range q {
		for j := range q[i] {
			s.q[i][j] = newBook(q[i][j], nil)
		}
	}
	return s
})

