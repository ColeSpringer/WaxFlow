// The SV8 canonical Huffman books, transcribed from libmpcdec's huffman.c. A
// row is a run of codewords of one length starting at the 16-bit code it
// names, and its value is the anchor the symbol table is indexed by:
// symbol = sym[(value - codeword) & 0xFF] (mpc_bits_can_dec). The symbols are
// the decoded values themselves: band counts, resolutions, scalefactor deltas,
// tuple indexes for the 5-step quantiser, samples for resolutions 3..8 (3 and
// 4 pack two samples into signed nibbles), and the high byte for 9 and up.

// canTable is one canonical book: its rows and its symbol table.
type canTable struct {
	name    string
	entries []huffEntry
	sym     []int8
}

