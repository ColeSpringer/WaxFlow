// sv8BookSet is the built SV8 decoders.
type sv8BookSet struct {
	scfi  [2]*vlc
	dscf  [2]*vlc
	bands *vlc
	res   [2]*vlc
	q1    *vlc
	q     [6][2]*vlc
	q9up  *vlc
}

var sv8Books = sync.OnceValue(func() *sv8BookSet {
	s := &sv8BookSet{
		bands: newBook(canBands.entries, canBands.sym),
		q1:    newBook(canQ1.entries, canQ1.sym),
		q9up:  newBook(canQ9up.entries, canQ9up.sym),
	}
	for i := range 2 {
		s.scfi[i] = newBook(canSCFI[i].entries, canSCFI[i].sym)
		s.dscf[i] = newBook(canDSCF[i].entries, canDSCF[i].sym)
		s.res[i] = newBook(canRes[i].entries, canRes[i].sym)
	}
	for i := range canQ {
		for j := range canQ[i] {
			s.q[i][j] = newBook(canQ[i][j].entries, canQ[i][j].sym)
		}
	}
	return s
})

// The SV8 5-step tuple decodes: an index in 0..124 stands for three samples
// in -2..2, least significant first.
var (
	idx8_50 = func() (t [125]int8) {
		for i := range t {
			t[i] = int8(i%5) - 2
		}
		return t
	}()
	idx8_51 = func() (t [125]int8) {
		for i := range t {
			t[i] = int8(i/5%5) - 2
		}
		return t
	}()
	idx8_52 = func() (t [125]int8) {
		for i := range t {
			t[i] = int8(i/25) - 2
		}
		return t
	}()
)

// huffQ2Var is the switching weight of each 5-step tuple: the sum of the three
// samples' magnitudes, which the reference tabulates as HuffQ2_var and which
// decides the book for the next tuple.
var huffQ2Var = func() (t [125]uint32) {
	for i := range t {
		t[i] = uint32(abs8(idx8_50[i]) + abs8(idx8_51[i]) + abs8(idx8_52[i]))
	}
	return t
}()

func abs8(v int8) int8 {
	if v < 0 {
		return -v
	}
	return v
}

